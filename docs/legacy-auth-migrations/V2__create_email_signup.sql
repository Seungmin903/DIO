-- DIO (1).sql의 회원/인증/약관 구조. 기존 다이어리 테이블은 변경하지 않는다.
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    nickname VARCHAR(30) NOT NULL,
    nickname_key VARCHAR(30) NOT NULL UNIQUE,
    profile_color CHAR(7) NOT NULL DEFAULT '#6F9FC6',
    birth_date DATE NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    last_login_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ NULL
);

CREATE TABLE user_auth_providers (
    auth_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    provider VARCHAR(20) NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (provider, provider_user_id),
    UNIQUE (user_id, provider)
);

CREATE TABLE user_terms_agreements (
    terms_type VARCHAR(20) NOT NULL,
    terms_version VARCHAR(10) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    agreed BOOLEAN NOT NULL,
    agreed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (terms_type, terms_version, user_id)
);

-- 가입 전 이메일 검증용. 인증번호는 HMAC, 가입 토큰은 SHA-256 해시만 보관한다.
CREATE TABLE signup_email_verifications (
    email VARCHAR(255) PRIMARY KEY,
    code_hash CHAR(64) NOT NULL,
    sent_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    token_hash CHAR(64) NULL,
    token_expires_at TIMESTAMPTZ NULL,
    consumed_at TIMESTAMPTZ NULL
);
