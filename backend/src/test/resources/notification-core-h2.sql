-- 기본 알림 계약 전용. watermark/이벤트 테이블 및 Hibernate DDL 없이 검증한다.
set mode PostgreSQL;
create table users(user_id bigint primary key, nickname varchar(30) not null, status varchar(20) default 'ACTIVE', deleted_at timestamp with time zone);
create table diaries(diary_id uuid primary key, deleted_at timestamp with time zone);
create table diary_members(diary_id uuid, user_id bigint, left_at timestamp with time zone);
create table diary_invites(invite_id bigint primary key, diary_id uuid, invitee_user_id bigint, invite_type varchar(30), revoked_at timestamp with time zone, use_count integer);
create table notifications(
    notification_id bigint generated by default as identity primary key,
    user_id bigint not null,
    actor_user_id bigint,
    diary_id uuid,
    page_id uuid,
    notification_type varchar(50) not null,
    payload_json jsonb,
    read_at timestamp(6) with time zone,
    deleted_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null
);
