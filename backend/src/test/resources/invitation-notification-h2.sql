-- 테스트 전용 복제 스키마: notifications 또는 V20 변경 시 이 fixture도 동기화하고 실제 PostgreSQL Flyway 테스트를 실행한다.
create table if not exists notifications(
    notification_id bigint generated by default as identity primary key,
    user_id bigint not null,
    actor_user_id bigint,
    diary_id uuid,
    page_id uuid,
    notification_type varchar(50) not null,
    payload_json jsonb,
    read_at timestamp(6) with time zone,
    deleted_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null
);

alter table notifications add column if not exists payload_json jsonb;
-- 초대 알림 재전달·동시 수신·삭제 후 재생성을 방지하는 처리 이력.
CREATE TABLE IF NOT EXISTS invitation_notification_receipts (
    event_id UUID NOT NULL,
    recipient_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    invite_id BIGINT NOT NULL,
    event_occurred_at timestamp(6) with time zone NOT NULL,
    outcome VARCHAR(30) NOT NULL,
    notification_id BIGINT REFERENCES notifications(notification_id) ON DELETE SET NULL,
    processed_at timestamp(6) with time zone NOT NULL,
    PRIMARY KEY (event_id, recipient_user_id),
    UNIQUE (event_id),
    UNIQUE (invite_id, recipient_user_id),
    CHECK (outcome IN ('PROCESSING', 'CREATED', 'SKIPPED_REVOKED', 'SKIPPED_EXPIRED', 'SKIPPED_INELIGIBLE'))
);

CREATE INDEX IF NOT EXISTS idx_invitation_notification_receipts_notification
    ON invitation_notification_receipts(notification_id);
