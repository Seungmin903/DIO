-- 비회원 로컬 개발용. 회원 도입 전에는 owner_user_id를 지정하지 않는다.
CREATE TABLE diaries (
    diary_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NULL,
    title VARCHAR(100) NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 100),
    cover_color CHAR(7) NOT NULL CHECK (cover_color ~ '^#[0-9A-Fa-f]{6}$'),
    cover_style VARCHAR(30) NOT NULL CHECK (cover_style IN ('LINEN','LEATHER','DOT','GINGHAM','STRIPE')),
    cover_binding VARCHAR(30) NOT NULL CHECK (char_length(btrim(cover_binding)) > 0),
    format_id VARCHAR(30) NOT NULL,
    canvas_width NUMERIC(10,2) NOT NULL CHECK (canvas_width > 0),
    canvas_height NUMERIC(10,2) NOT NULL CHECK (canvas_height > 0),
    default_page_template VARCHAR(20) NOT NULL CHECK (default_page_template IN ('MONTHLY','WEEKLY','BLANK','LINED','SQUARED','DOTTED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
