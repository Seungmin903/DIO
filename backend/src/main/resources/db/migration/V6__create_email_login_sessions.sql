-- 일반 로그인 세션 전용. 기존 회원/다이어리 및 V1~V5는 변경하지 않는다.
CREATE TABLE refresh_tokens (
    token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    device_name VARCHAR(100),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX refresh_tokens_user_id_idx ON refresh_tokens(user_id);
-- 원문은 보관하지 않는다. 사용된 토큰 재사용 시 해당 세션을 종료한다.
CREATE TABLE refresh_token_history (
    token_hash CHAR(64) PRIMARY KEY,
    token_id BIGINT NOT NULL REFERENCES refresh_tokens(token_id) ON DELETE CASCADE,
    rotated_at TIMESTAMPTZ NOT NULL
);
