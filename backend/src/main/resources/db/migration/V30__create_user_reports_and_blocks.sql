CREATE TABLE user_reports (
 report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reporter_user_id BIGINT NOT NULL REFERENCES users(user_id),
 reported_user_id BIGINT NOT NULL REFERENCES users(user_id),
 diary_id UUID NOT NULL,
 client_request_id UUID NOT NULL,
 request_hash VARCHAR(64) NOT NULL,
 reason_code VARCHAR(40) NOT NULL,
 description VARCHAR(1000),
 evidence_json JSONB NOT NULL DEFAULT '[]'::jsonb,
 status VARCHAR(20) NOT NULL DEFAULT 'RECEIVED',
 action_type VARCHAR(30), action_expires_at TIMESTAMPTZ,
 resolution_note TEXT, handled_by VARCHAR(100),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 resolved_at TIMESTAMPTZ,
 notification_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 notification_attempts INTEGER NOT NULL DEFAULT 0,
 notification_next_attempt_at TIMESTAMPTZ,
 history_json JSONB NOT NULL DEFAULT '[]'::jsonb,
 CONSTRAINT uq_report_request UNIQUE(reporter_user_id,client_request_id),
 CONSTRAINT ck_report_not_self CHECK(reporter_user_id<>reported_user_id),
 CONSTRAINT ck_report_reason CHECK(reason_code IN ('HARASSMENT','HATE_DISCRIMINATION','SEXUAL_CONTENT','THREAT_PRIVACY','CHILD_SAFETY','SPAM_FRAUD','RIGHTS_INFRINGEMENT','COLLABORATION_ABUSE','OTHER')),
 CONSTRAINT ck_report_description CHECK(reason_code<>'OTHER' OR length(trim(description))>0 AND description IS NOT NULL),
 CONSTRAINT ck_report_status CHECK(status IN ('RECEIVED','REVIEWING','RESOLVED','DISMISSED')),
 CONSTRAINT ck_report_notification CHECK(notification_status IN ('PENDING','SENT','FAILED'))
);
CREATE INDEX ix_report_status_created ON user_reports(status,created_at);
CREATE INDEX ix_report_target_created ON user_reports(reported_user_id,created_at);
CREATE INDEX ix_report_actor_created ON user_reports(reporter_user_id,created_at);
CREATE INDEX ix_report_mail_due ON user_reports(notification_status,notification_next_attempt_at);
CREATE TABLE user_blocks (
 blocker_user_id BIGINT NOT NULL REFERENCES users(user_id),
 blocked_user_id BIGINT NOT NULL REFERENCES users(user_id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(blocker_user_id,blocked_user_id),
 CONSTRAINT ck_block_not_self CHECK(blocker_user_id<>blocked_user_id)
);
CREATE INDEX ix_block_reverse ON user_blocks(blocked_user_id,blocker_user_id);
CREATE INDEX ix_block_actor_created ON user_blocks(blocker_user_id,created_at);
