// Isolated, ephemeral browser profile + localhost fixture; no user app data.
const { chromium } = require('playwright-core')
const http = require('node:http'), fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const output = path.join(__dirname, '../.expo/qa/sticker-workspace')
fs.mkdirSync(output, { recursive: true })
const metroPort = process.env.STICKER_QA_PORT || '54861'
const server = http.createServer((req, res) => {
  if (req.url === '/') {
    res.setHeader('Content-Type', 'text/html')
    res.end('<!doctype html><meta name="viewport" content="width=device-width,initial-scale=1"><body style="margin:0"><div id="root" style="display:flex;height:100dvh"></div><script src="/tests/fixtures/sticker-workspace.entry.bundle?platform=web&dev=false&minify=false&hot=false&lazy=false"></script>')
  } else {
    const upstream = http.get(`http://localhost:${metroPort}${req.url}`, r => { res.writeHead(r.statusCode, r.headers); r.pipe(res) })
    upstream.on('error', e => { res.writeHead(502); res.end(e.message) })
  }
})
;(async () => {
  let browser
  try {
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
    browser = await chromium.launch({ channel: 'msedge', headless: true })
    for (const [width, height] of [[320,740], [375,812], [414,896], [768,1024], [1280,800], [844,390]]) {
      const context = await browser.newContext({ viewport: { width, height } })
      const page = await context.newPage(), errors = []
      page.on('pageerror', error => errors.push(error.message)); page.setDefaultTimeout(20000)
      const button = name => page.getByRole(['배경 조정','포함·제외','객체 묶기','스티커 확인'].includes(name) ? 'tab' : 'button', { name, exact: true })
      await page.goto(`http://127.0.0.1:${server.address().port}`)
      await button('분리하기').waitFor({ timeout: 180000 })
      assert.equal(await button('배경 조정').getAttribute('aria-selected'), 'true')
      assert.equal(await page.getByLabel('배경 허용 범위', { exact: true }).getAttribute('aria-valuenow'), '10')
      const autoBox = await button('자동 배경').boundingBox(), manualBox = await button('배경 직접 지정').boundingBox()
      assert.ok(autoBox.height >= 44 && manualBox.height >= 44 && Math.abs(autoBox.y - manualBox.y) < 1)
      assert.deepEqual(await page.getByRole('tab').allTextContents(), ['배경 조정','포함·제외','객체 묶기','스티커 확인'])
      await page.getByTestId('sticker-tool-status').getByText('자동', { exact: true }).waitFor()
      await page.waitForFunction(() => !document.querySelector('[aria-label="분리하기"]').hasAttribute('disabled') && document.querySelector('[aria-label="분리하기"]').getAttribute('aria-disabled') !== 'true')
      await button('배경 직접 지정').click()
      const pinPreview = page.getByTestId('sticker-split-preview'); await pinPreview.scrollIntoViewIfNeeded()
      const pinFrame = await pinPreview.boundingBox(), pinScale = Math.min(pinFrame.width / 800, pinFrame.height / 1000)
      await page.mouse.click(pinFrame.x + (pinFrame.width - 800 * pinScale) / 2 + 5 * pinScale, pinFrame.y + (pinFrame.height - 1000 * pinScale) / 2 + 5 * pinScale)
      const tag = page.getByTestId('sticker-background-tag'); await tag.waitFor()
      const tagBox = await tag.boundingBox()
      const toolBox = await page.getByTestId('sticker-active-tool').boundingBox()
      assert.ok(tagBox.y >= toolBox.y + toolBox.height || tagBox.x >= toolBox.x + toolBox.width)
      assert.ok(tagBox.x >= pinFrame.x && tagBox.x + tagBox.width <= pinFrame.x + pinFrame.width + 1)
      assert.ok(tagBox.y >= pinFrame.y && tagBox.y + tagBox.height <= pinFrame.y + pinFrame.height + 1)
      await page.screenshot({ path: path.join(output, `background-tag-${width}.png`) })
      await page.mouse.click(pinFrame.x + (pinFrame.width - 800 * pinScale) / 2 + 54 * pinScale, pinFrame.y + (pinFrame.height - 1000 * pinScale) / 2 + 52 * pinScale)
      await page.getByTestId('sticker-background-swatch').screenshot({ path: path.join(output, `background-swatch-${width}.png`) })
      await button('자동 배경').click(); await tag.waitFor({ state: 'detached' })
      await button('분리하기').click()
      await button('32개 저장').waitFor()
      assert.equal(await button('스티커 확인').getAttribute('aria-selected'), 'true')
      const saveBox = await button('32개 저장').boundingBox()
      assert.ok(saveBox.y >= 0 && saveBox.y + saveBox.height <= height + 1, JSON.stringify({ width, height, saveBox }))
      assert.equal(await button('32개 저장').textContent(), '저장')
      assert.ok((await page.getByTestId('sticker-save-row').boundingBox()).height <= 80)
      assert.ok((await button('스티커 확인').boundingBox()).height <= 48)
      const first = button('스티커 1 확인'); await first.click()
      assert.equal(await page.getByRole('checkbox', { name: '스티커 1 저장 포함', exact: true }).getAttribute('aria-checked'), 'true')
      await page.getByRole('checkbox', { name: '스티커 1 저장 포함', exact: true }).click()
      await button('31개 저장').waitFor()
      await button('목록 더보기').click(); await button('모두 선택').click()
      await button('32개 저장').waitFor()
      await button('객체 묶기').click()
      assert.equal(await button('스티커 확인').getAttribute('aria-selected'), 'false')
      await button('직접 묶기').click()
      await page.getByRole('button', { name: '스티커 1 묶기 대상으로 선택', exact: true }).click()
      await page.getByRole('button', { name: '스티커 2 묶기 대상으로 선택', exact: true }).click()
      await page.getByRole('button', { name: '스티커 3 묶기 대상으로 선택', exact: true }).click()
      await button('선택한 항목 묶기').click()
      await button('30개 저장').waitFor()
      await button('객체 묶기').click(); await button('직접 분리').click()
      await page.getByLabel('분리 브러시 굵기', { exact: true }).waitFor()
      const original = page.getByTestId('sticker-split-preview')
      await original.scrollIntoViewIfNeeded()
      const frame = await original.boundingBox(), scale = Math.min(frame.width / 800, frame.height / 1000)
      const x = frame.x + (frame.width - 800 * scale) / 2 + 678 * scale
      const y = frame.y + (frame.height - 1000 * scale) / 2 + 308 * scale
      await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + 4, y + 4, { steps: 3 }); await page.mouse.up()
      await button('31개 저장').waitFor()
      await button('실행 취소').click(); await button('30개 저장').waitFor()
      await button('다시 실행').click(); await button('31개 저장').waitFor()
      await button('직접 분리').click()
      await button('포함·제외').click()
      assert.equal(await button('포함·제외').getAttribute('aria-selected'), 'true')
      await button('추가 브러시').click()
      await button('포함·제외').click()
      assert.equal(await button('31개 저장').count(), 1)
      await button('배경 조정').click()
      await button('자동 배경').waitFor()
      await button('스티커 확인').click()
      const preview = await button('영역 조정').boundingBox()
      if (width >= 768 && height >= 500) {
        assert.ok(preview.x < width / 2 + 16, JSON.stringify({ width, preview }))
        assert.ok(saveBox.x >= width / 2 - 16, JSON.stringify({ width, saveBox }))
      }
      await page.screenshot({ path: path.join(output, `workspace-${width}x${height}.png`) })
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
      assert.equal(overflow, false)
      assert.deepEqual(errors, [])
      console.log(`PASS ${width}×${height}: browser-style tabs/status, background tag, 3-member group → touched member + remaining pair, undo/redo, fixed action, no horizontal overflow`)
      await context.close()
    }
  } finally { await browser?.close(); server.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
