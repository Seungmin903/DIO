const {chromium} = require('playwright-core')
const http = require('node:http'), fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const output = path.join(__dirname, '../.expo/reading-mode-qa')
fs.mkdirSync(output, {recursive:true})
const server = http.createServer((req,res)=>{
  if (req.url.split('?')[0] === '/') {
    res.setHeader('Content-Type','text/html')
    res.end('<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body style="margin:0"><div id="root" style="display:flex;height:100dvh"></div><script src="/tests/fixtures/reading-mode.entry.bundle?platform=web&dev=false&minify=false&hot=false&lazy=false"></script></body></html>')
  } else {
    const upstream=http.get('http://'+(process.env.EXPO_QA_HOST || '127.0.0.1')+':'+(process.env.EXPO_QA_PORT || '54841')+req.url,r=>{res.writeHead(r.statusCode,r.headers);r.pipe(res)})
    upstream.on('error',e=>{res.writeHead(502);res.end(e.message)})
  }
})
async function main() {
  await new Promise(r=>server.listen(54842,'127.0.0.1',r))
  const browser=await chromium.launch({executablePath:process.env.BROWSER_EXECUTABLE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true})
  try {
    for(const [width,height] of [[320,740],[375,812],[844,390],[1024,768],[1280,800]]) {
      const context=await browser.newContext({viewport:{width,height},hasTouch:true})
      const page=await context.newPage(), errors=[]
      page.on('pageerror',e=>errors.push(e.message))
      await page.goto('http://127.0.0.1:54842')
      await page.waitForFunction(()=>window.__readerState?.loaded,null,{timeout:180000})
      const enter=page.getByRole('button',{name:'읽기 모드로 전환',exact:true})
      const initial=await page.evaluate(()=>({doc:window.__readerState.docJSON,past:window.__readerState.past}))
      await enter.click()
      await page.getByRole('button',{name:'편집 모드로 전환',exact:true}).waitFor()
      const after=await page.getByRole('button',{name:'편집 모드로 전환',exact:true}).boundingBox(),fitAfter=await page.getByRole('button',{name:'화면에 맞춤',exact:true}).boundingBox()
      const menu=page.getByTestId('reading-bottom-menu'), menuBox=await menu.boundingBox()
      assert.equal(await menu.getByRole('button',{name:'화면에 맞춤',exact:true}).count(),1)
      assert.equal(await menu.getByRole('button',{name:'편집 모드로 전환',exact:true}).count(),1)
      assert.equal(await page.getByRole('button',{name:'화면에 맞춤',exact:true}).count(),1)
      for(const box of [after,fitAfter]) assert.ok(box.x>=menuBox.x && box.x+box.width<=menuBox.x+menuBox.width+1,'Reading controls stay inside one menu')
      assert.ok(after.width>=44 && after.height>=44)
      assert.equal(await page.getByLabel('되돌리기',{exact:true}).count(),0)
      await page.getByRole('button',{name:'다음 페이지',exact:true}).click()
      await page.waitForFunction(()=>window.__readerState.pageId==='reader-page-1')
      // Canvas areas are viewport-relative, and the menu must not change its geometry.
      const canvas=page.getByLabel('다이어리 읽기 캔버스',{exact:true}), canvasBefore=await canvas.boundingBox()
      await page.mouse.click(width/2,height/2)
      await page.getByRole('button',{name:'편집 모드로 전환',exact:true}).waitFor({state:'hidden'})
      assert.deepEqual(await canvas.boundingBox(),canvasBefore)
      await page.mouse.click(width/2,height/2)
      await page.getByRole('button',{name:'편집 모드로 전환',exact:true}).waitFor()
      await page.mouse.click(width-8,height/2)
      await page.waitForFunction(()=>window.__readerState.pageId==='reader-page-2')
      // Mouse drag uses the same RN responder route as a one-finger swipe on web.
      await page.mouse.move(width*.7,height*.5); await page.mouse.down(); await page.mouse.move(width*.3,height*.5,{steps:8}); await page.mouse.up()
      await page.waitForFunction(()=>window.__readerState.pageId==='reader-page-3')
      // Holding either arrow repeats, stops at the page boundary and adds nothing on release.
      let arrow=await page.getByRole('button',{name:'다음 페이지',exact:true}).boundingBox()
      await page.mouse.move(arrow.x+arrow.width/2,arrow.y+arrow.height/2);await page.mouse.down()
      await page.waitForFunction(()=>window.__readerState.pageId==='reader-page-4')
      await page.mouse.up()
      assert.equal(await page.evaluate(()=>window.__readerState.pageId),'reader-page-4')
      arrow=await page.getByRole('button',{name:'이전 페이지',exact:true}).boundingBox()
      await page.mouse.move(arrow.x+arrow.width/2,arrow.y+arrow.height/2);await page.mouse.down()
      await page.waitForFunction(()=>window.__readerState.pageId==='reader-page-0')
      await page.mouse.up()
      for(let i=0;i<3;i++) await page.getByRole('button',{name:'다음 페이지',exact:true}).click()
      const docState=await page.evaluate(()=>({doc:window.__readerState.docJSON,past:window.__readerState.past}))
      assert.deepEqual(docState,initial)
      await page.screenshot({path:path.join(output,`reader-${width}x${height}.png`)})
      await page.getByRole('button',{name:'편집 모드로 전환',exact:true}).click()
      await enter.waitFor()
      assert.equal(await page.evaluate(()=>window.__readerState.pageId),'reader-page-3')
      await page.reload(); await page.waitForFunction(()=>window.__readerState?.loaded)
      assert.equal(await page.evaluate(()=>window.__readerState.pageId),'reader-page-3')
      assert.equal(await page.evaluate(()=>window.__readerState.reading),false)
      await page.goto('http://127.0.0.1:54842?readonly'); await page.waitForFunction(()=>window.__readerState?.loaded)
      await page.getByRole('button',{name:'다음 페이지',exact:true}).waitFor()
      assert.equal(await page.getByRole('button',{name:'편집 모드로 전환',exact:true}).count(),0)
      assert.equal(await page.getByRole('button',{name:'읽기 모드로 전환',exact:true}).count(),0)
      if(width===1280) {
        for(let i=0;i<3;i++) await page.getByRole('button',{name:'이전 페이지',exact:true}).click()
        await page.waitForFunction(()=>window.__readerState.pageId==='reader-page-0')
        await page.evaluate(()=>{window.open=(url)=>{window.__openedReaderLink=url;return null}})
        await page.getByRole('link').first().click()
        assert.equal(await page.evaluate(()=>window.__openedReaderLink),'https://example.com/')
        assert.equal(await page.evaluate(()=>window.__readerState.pageId),'reader-page-0')
        assert.equal(await page.getByRole('button',{name:'다음 페이지',exact:true}).isVisible(),true)
        const linkBox=await page.getByRole('link').first().boundingBox()
        await page.evaluate(()=>{window.__openedReaderLink=null})
        await page.mouse.move(linkBox.x+linkBox.width/2,linkBox.y+linkBox.height/2)
        await page.mouse.down()
        await page.mouse.move(linkBox.x+linkBox.width/2-100,linkBox.y+linkBox.height/2,{steps:8})
        await page.mouse.up()
        await page.waitForFunction(()=>window.__readerState.pageId==='reader-page-1')
        assert.equal(await page.evaluate(()=>window.__openedReaderLink),null)
        await page.getByRole('button',{name:'이전 페이지',exact:true}).click()
        const cdp=await context.newCDPSession(page)
        const touch=(type,points)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:points})
        await touch('touchStart',[{x:500,y:350,id:1},{x:600,y:350,id:2}])
        await touch('touchMove',[{x:450,y:350,id:1},{x:650,y:350,id:2}])
        await touch('touchEnd',[])
        await page.waitForFunction(()=>window.__readerState.view.scale>1)
        await touch('touchStart',[{x:600,y:400,id:1}])
        await new Promise(resolve=>setTimeout(resolve,280))
        await touch('touchMove',[{x:570,y:400,id:1}])
        await touch('touchMove',[{x:400,y:400,id:1}])
        await touch('touchEnd',[])
        assert.equal(await page.evaluate(()=>window.__readerState.pageId),'reader-page-0')
        assert.ok((await page.evaluate(()=>window.__readerState.view.scale))>1)
        // A separate fast horizontal swipe now turns one page even while zoomed.
        await touch('touchStart',[{x:600,y:400,id:1}])
        await touch('touchMove',[{x:400,y:400,id:1}])
        await touch('touchEnd',[])
        await page.waitForFunction(()=>window.__readerState.pageId==='reader-page-1' && window.__readerState.view.scale===1)
        await page.mouse.click(width-8,height/2)
        await page.waitForFunction(()=>window.__readerState.pageId==='reader-page-2' && window.__readerState.view.scale===1)
        await cdp.detach()
        await page.goto('http://127.0.0.1:54842')
        await page.waitForFunction(()=>window.__readerState?.loaded)
        await page.getByLabel('텍스트',{exact:true}).click()
        // First outside tap closes the text settings, following the normal editor flow.
        await page.mouse.click(1200,200)
        await page.getByLabel('드래그하여 텍스트 상자 만들기',{exact:true}).click({position:{x:200,y:200}})
        const input=page.getByLabel('캔버스 텍스트 내용',{exact:true})
        await input.waitFor();await input.fill('전환 전 입력 보존')
        await page.getByRole('button',{name:'읽기 모드로 전환',exact:true}).click()
        await page.waitForFunction(()=>window.__readerState.reading && window.__readerState.docJSON.includes('전환 전 입력 보존'))
        console.log('PASS touch pinch, slow-drag lock, zoomed fast swipe, link priority, edge tap, text draft commit')
      }
      assert.deepEqual(errors,[])
      console.log(`PASS ${width}x${height}: integrated menu, hold-to-repeat boundaries, page turn, unchanged document, last page, permissions`)
      await context.close()
    }
  } finally {await browser.close();server.close()}
}
main().catch(e=>{console.error(e);server.close();process.exitCode=1})
