"""Generate font-independent app SVGs from the editable tasting-note v2 drafts."""
from pathlib import Path
import json
import re
import xml.etree.ElementTree as ET
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

root = Path(__file__).resolve().parents[1]
font = TTFont(root / 'node_modules/@expo-google-fonts/poor-story/400Regular/PoorStory_400Regular.ttf')
glyphs, cmap, units = font.getGlyphSet(), font.getBestCmap(), font['head'].unitsPerEm
ns = '{http://www.w3.org/2000/svg}'
ET.register_namespace('', ns[1:-1])
styles = {
    'guide': {'fill': 'none', 'stroke': '#b7babd', 'stroke-width': '1.25'},
    'icon': {'fill': 'none', 'stroke': '#252525', 'stroke-width': '2.1', 'stroke-linecap': 'round', 'stroke-linejoin': 'round'},
    'choice': {'fill': 'none', 'stroke': '#777c80', 'stroke-width': '1.8'},
}

def convert(orientation):
    svg = ET.parse(root / f'assets/templates/tasting-note-v2/source-{orientation}.svg').getroot()
    def visit(parent):
        for child in list(parent):
            tag = child.tag.removeprefix(ns)
            if tag in ('style', 'title', 'desc') or child.get('id') == 'photo-placeholder' or tag == 'text' and child.text == '사진 추가':
                parent.remove(child)
                continue
            if tag == 'text':
                label = child.text or ''
                classes = (child.get('class') or '').split()
                size = float(child.get('font-size') or (20 if 'option' in classes else 23))
                x, y = float(child.get('x')), float(child.get('y'))
                scale = size / units
                pen = SVGPathPen(glyphs)
                for char in label:
                    name = cmap.get(ord(char))
                    if name is None:
                        raise ValueError(f'Missing glyph: {char}')
                    glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, y)))
                    x += glyphs[name].width * scale
                path = ET.Element(ns + 'path', {'d': pen.getCommands(), 'aria-label': label, 'fill': '#202020', 'stroke': '#202020', 'stroke-width': '0.6', 'stroke-linejoin': 'round', 'paint-order': 'stroke fill'})
                index = list(parent).index(child)
                parent.remove(child)
                parent.insert(index, path)
                continue
            for cls in (child.attrib.pop('class', '')).split():
                child.attrib.update(styles.get(cls, {}))
            visit(child)
    visit(svg)
    return re.sub(r'(?m)^[ \t]+$', '', ET.tostring(svg, encoding='unicode', short_empty_elements=True))

result = {orientation: convert(orientation) for orientation in ('portrait', 'landscape')}
assets = root / 'assets/templates/tasting-note-v2'
assets.mkdir(parents=True, exist_ok=True)
for orientation, svg in result.items():
    (assets / f'tasting-{orientation}.svg').write_text(svg, encoding='utf-8', newline='\n')
module = '// Generated by scripts/build-tasting-v2.py.\n' + ''.join(f'export const TASTING_V2_{key.upper()}_SVG = {json.dumps(value, ensure_ascii=False)}\n' for key, value in result.items())
(root / 'src/editor/templates/tastingV2Svg.js').write_text(module, encoding='utf-8', newline='\n')
