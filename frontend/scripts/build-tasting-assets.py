"""Convert the approved editable SVGs to app SVGs with embedded glyph outlines.

Usage: python build-tasting-assets.py <portrait.svg> <landscape.svg>
Requires fonttools and the Poor Story font from the frontend dependencies.
"""
from pathlib import Path
import json
import sys
import xml.etree.ElementTree as ET
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

root = Path(__file__).resolve().parents[1]
font = TTFont(root / 'node_modules/@expo-google-fonts/poor-story/400Regular/PoorStory_400Regular.ttf')
glyphs, cmap, units = font.getGlyphSet(), font.getBestCmap(), font['head'].unitsPerEm
ns = '{http://www.w3.org/2000/svg}'
ET.register_namespace('', ns[1:-1])
styles = {
    'guide': {'fill': 'none', 'stroke': '#a5a6aa', 'stroke-width': '1.5', 'stroke-linecap': 'round', 'stroke-linejoin': 'round'},
    'icon': {'fill': 'none', 'stroke': '#202124', 'stroke-width': '2.4', 'stroke-linecap': 'round', 'stroke-linejoin': 'round'},
    'mark': {'fill': 'none', 'stroke': '#767a7f', 'stroke-width': '2.4', 'stroke-linejoin': 'round'},
}

def convert(source, orientation):
    original = ET.parse(source).getroot()
    source_w, source_h = (1058, 1487) if orientation == 'portrait' else (1487, 1058)
    width, height = (768, 1024) if orientation == 'portrait' else (1024, 768)
    svg = ET.Element(ns + 'svg', {'viewBox': f'0 0 {width} {height}', 'width': str(width), 'height': str(height)})
    ET.SubElement(svg, ns + 'rect', {'width': str(width), 'height': str(height), 'fill': '#FFFFFF'})
    group = ET.SubElement(svg, ns + 'g', {'transform': f'scale({width/source_w:.10f} {height/source_h:.10f})'})
    for child in original:
        tag = child.tag.removeprefix(ns)
        if tag in ('defs', 'title', 'desc') or child.get('id') in ('paper', 'photo-placeholder'):
            continue
        if child.get('id') == 'labels':
            labels = ET.SubElement(group, ns + 'g', {'id': 'labels', 'fill': '#111111', 'stroke': '#111111', 'stroke-width': '1.15', 'stroke-linejoin': 'round', 'paint-order': 'stroke fill'})
            for element in child:
                text = element.text or ''
                size, x, y = float(element.get('font-size')), float(element.get('x')), float(element.get('y'))
                scale = size / units
                pen = SVGPathPen(glyphs)
                for ch in text:
                    name = cmap[ord(ch)]
                    glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, y)))
                    x += glyphs[name].width * scale
                attrs = {'d': pen.getCommands(), 'aria-label': text}
                if element.get('id'):
                    attrs['id'] = element.get('id')
                ET.SubElement(labels, ns + 'path', attrs)
        else:
            kind = child.attrib.pop('class', None)
            if kind:
                child.attrib.update(styles[kind])
            group.append(child)
    return ET.tostring(svg, encoding='unicode', short_empty_elements=True)

result = {orientation: convert(Path(path), orientation) for orientation, path in zip(('portrait', 'landscape'), sys.argv[1:])}
if len(result) != 2:
    raise SystemExit('Both portrait and landscape SVGs are required')
assets = root / 'assets/templates/tasting-note'
assets.mkdir(parents=True, exist_ok=True)
for orientation, svg in result.items():
    (assets / f'tasting-{orientation}.svg').write_text(svg, encoding='utf-8', newline='\n')
module = '// Generated by scripts/build-tasting-assets.py.\n' + ''.join(f'export const TASTING_{key.upper()}_SVG = {json.dumps(value, ensure_ascii=False)}\n' for key, value in result.items())
(root / 'src/editor/templates/tastingReferenceSvg.js').write_text(module, encoding='utf-8', newline='\n')
print('App SVG assets generated')
